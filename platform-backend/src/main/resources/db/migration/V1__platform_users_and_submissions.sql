CREATE TABLE sys_user (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(32) NOT NULL UNIQUE,
    password_hash varchar(72) NOT NULL,
    role varchar(16) NOT NULL CHECK (role IN ('STUDENT', 'TEACHER', 'ADMIN')),
    name varchar(64) NOT NULL,
    major varchar(64),
    teacher_id bigint REFERENCES sys_user(id) ON DELETE RESTRICT,
    must_change_password boolean NOT NULL DEFAULT true,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT user_account_format CHECK (username ~ '^[A-Za-z0-9_]{3,32}$'),
    CONSTRAINT student_fields_only CHECK (role = 'STUDENT' OR (major IS NULL AND teacher_id IS NULL)),
    CONSTRAINT no_self_teacher CHECK (teacher_id IS NULL OR teacher_id <> id)
);
CREATE INDEX idx_user_teacher ON sys_user(teacher_id);
CREATE INDEX idx_user_role_active ON sys_user(role, is_active);

CREATE TABLE submission (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL REFERENCES sys_user(id) ON DELETE RESTRICT,
    original_filename varchar(255) NOT NULL,
    file_size bigint NOT NULL CHECK (file_size > 0),
    status varchar(16) NOT NULL CHECK (status IN ('PENDING', 'PROCESSING', 'SUCCESS', 'FAILED')),
    storage_dir varchar(255) NOT NULL UNIQUE,
    problem_count integer NOT NULL DEFAULT 0 CHECK (problem_count >= 0),
    by_scope jsonb,
    error_message varchar(500),
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    started_at timestamptz,
    finished_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);
CREATE INDEX idx_submission_student_created ON submission(student_id, created_at DESC, id DESC);
CREATE INDEX idx_submission_status ON submission(status);
