ALTER TABLE sys_user ADD COLUMN college_code varchar(32);
ALTER TABLE sys_user ADD CONSTRAINT user_college_code CHECK (college_code IS NULL OR college_code IN
    ('INFORMATION_ENGINEERING', 'EDUCATION_ARTS', 'ECONOMICS_MANAGEMENT'));
CREATE INDEX idx_user_college_role ON sys_user(college_code, role, is_active);

CREATE TABLE major_catalog (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_code varchar(32) NOT NULL CHECK (college_code IN
        ('INFORMATION_ENGINEERING', 'EDUCATION_ARTS', 'ECONOMICS_MANAGEMENT')),
    name varchar(64) NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    CONSTRAINT uq_major_college_name UNIQUE (college_code, name)
);
CREATE INDEX idx_major_college_active ON major_catalog(college_code, is_active);
