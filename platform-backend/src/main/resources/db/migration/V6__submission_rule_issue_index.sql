ALTER TABLE submission
    ADD COLUMN rule_index_status varchar(16) NOT NULL DEFAULT 'PENDING',
    ADD COLUMN rule_index_attempts integer NOT NULL DEFAULT 0,
    ADD COLUMN rule_index_next_retry_at timestamptz;

ALTER TABLE submission
    ADD CONSTRAINT submission_rule_index_status_check
        CHECK (rule_index_status IN ('PENDING', 'READY', 'UNAVAILABLE')),
    ADD CONSTRAINT submission_rule_index_attempts_check
        CHECK (rule_index_attempts >= 0);

CREATE INDEX idx_submission_rule_index_backfill
    ON submission (rule_index_status, rule_index_next_retry_at, id)
    WHERE status = 'SUCCESS';

CREATE TABLE submission_rule_issue (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id bigint NOT NULL REFERENCES submission(id) ON DELETE RESTRICT,
    rule_id varchar(128) NOT NULL,
    description varchar(500) NOT NULL,
    issue_count integer NOT NULL CHECK (issue_count > 0),
    CONSTRAINT submission_rule_issue_unique UNIQUE (submission_id, rule_id)
);
CREATE INDEX idx_submission_rule_issue_rule ON submission_rule_issue(rule_id);
